"""Upstream model prediction provider interface and mock adapter.

Security and Operational Invariants:
- Real Vertex AI calls remain disabled in local development and testing.
- The service authenticates to Vertex AI using server-side credentials only (ADC or Cloud Run service account).
- Endpoint IDs and Google Cloud project details are strictly isolated from API consumers.
- MockModelProvider generates deterministic responses with accurate token counts for local testing.
"""

from __future__ import annotations

import logging
import time
from dataclasses import dataclass
from typing import Any, Protocol

from fastapi import HTTPException, status
import httpx

try:
    import google.auth
    import google.auth.transport.requests
    _HAS_GOOGLE_AUTH = True
except ImportError:
    _HAS_GOOGLE_AUTH = False
    google = None  # type: ignore[assignment]

from app.config import Settings
from app.models import RegisteredModel
from app.schemas import ChatMessage

logger = logging.getLogger(__name__)


from pydantic import BaseModel, ConfigDict, Field, model_validator


class PredictionResult(BaseModel):
    """Result of an upstream model prediction.

    Attributes:
        content: Text content generated by the model.
        tokens_in: Strictly non-negative integer prompt tokens.
        tokens_out: Strictly non-negative integer completion tokens.
        latency_ms: Strictly non-negative execution time in milliseconds.
        finish_reason: Reason generation stopped ('stop', 'length', etc.).
    """

    model_config = ConfigDict(extra="forbid", frozen=True)

    content: str
    tokens_in: int = Field(..., ge=0, strict=True, description="Strictly non-negative integer prompt tokens.")
    tokens_out: int = Field(..., ge=0, strict=True, description="Strictly non-negative integer completion tokens.")
    latency_ms: int = Field(..., ge=0, strict=True, description="Strictly non-negative execution time in milliseconds.")
    finish_reason: str = Field(default="stop", max_length=32)

    @model_validator(mode="after")
    def validate_token_consistency(self) -> PredictionResult:
        """Enforce that non-empty completion text generated by a model cannot consume zero tokens."""
        if bool(self.content.strip()) and self.tokens_out == 0:
            raise ValueError("Inconsistent token accounting: non-empty content with zero completion tokens.")
        return self


class BaseModelProvider(Protocol):
    """Protocol defining the interface for model inference providers."""

    async def predict(
        self,
        model: RegisteredModel,
        messages: list[ChatMessage],
        temperature: float = 0.7,
        max_tokens: int | None = None,
    ) -> PredictionResult:
        """Execute a prediction against the model provider."""
        ...


class MockModelProvider:
    """Deterministic in-memory mock provider for local development and test suites.

    Computes accurate token counts using character-based heuristic and returns
    deterministic text responses without making network or cloud calls.
    """

    def __init__(self, latency_ms: int = 15) -> None:
        self.latency_ms = latency_ms

    async def predict(
        self,
        model: RegisteredModel,
        messages: list[ChatMessage],
        temperature: float = 0.7,
        max_tokens: int | None = None,
    ) -> PredictionResult:
        start_time = time.monotonic()

        # Calculate prompt tokens: ~4 chars per token + 4 overhead tokens per message
        prompt_chars = sum(len(m.content) for m in messages)
        tokens_in = max(1, (prompt_chars + 3) // 4 + len(messages) * 4)

        last_user_msg = next(
            (m.content for m in reversed(messages) if m.role == "user"),
            messages[-1].content if messages else "Hello",
        )
        snippet = last_user_msg[:40].strip()

        # Deterministic generated text
        content = (
            f"Rantera [{model.model_id}]: Evaluation response for query '{snippet}'. "
            "Internal model evaluation complete."
        )

        tokens_out = max(1, (len(content) + 3) // 4)
        finish_reason = "stop"

        if max_tokens is not None and tokens_out > max_tokens:
            content = content[: max_tokens * 4]
            tokens_out = max_tokens
            finish_reason = "length"

        elapsed_ms = max(1, int((time.monotonic() - start_time) * 1000) + self.latency_ms)

        return PredictionResult(
            content=content,
            tokens_in=tokens_in,
            tokens_out=tokens_out,
            latency_ms=elapsed_ms,
            finish_reason=finish_reason,
        )


class VertexModelProvider:
    """Production Vertex AI provider using server-side Google Cloud credentials and :rawPredict.

    Security & Operational Invariants:
    - Authenticates using Google Application Default Credentials or attached service account.
    - Uses the Vertex AI :rawPredict protocol to pass OpenAI Chat Completion payloads
      directly to the custom vLLM container route (/v1/chat/completions).
    - Secret tokens and endpoint IDs are never exposed in client responses or exception logs.
    - Response parsing validates strictly non-negative integer tokens and latency.
    """

    def __init__(
        self,
        settings: Settings,
        client: httpx.AsyncClient | None = None,
        credentials: Any = None,
        timeout_seconds: float = 60.0,
    ) -> None:
        self.settings = settings
        self._client = client
        self._credentials = credentials
        self.timeout_seconds = timeout_seconds

    def _resolve_token(self) -> str:
        """Resolve a valid Google Cloud OAuth2 Bearer token safely."""
        if self._credentials is not None:
            creds = self._credentials
            if hasattr(creds, "valid") and not creds.valid and hasattr(creds, "refresh"):
                try:
                    if _HAS_GOOGLE_AUTH and google is not None:
                        auth_req = google.auth.transport.requests.Request()
                        creds.refresh(auth_req)
                    else:
                        creds.refresh()
                except Exception as exc:
                    logger.error("Failed to refresh Google credentials: %s", type(exc).__name__)
                    raise HTTPException(
                        status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                        detail="Failed to refresh Google Cloud authentication credentials.",
                    )
            token = getattr(creds, "token", None)
            if token:
                return str(token)
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Google Cloud credentials token is unavailable.",
            )

        if not _HAS_GOOGLE_AUTH or google is None:
            logger.error("google-auth library is not installed; cannot authenticate with Vertex AI.")
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Google authentication library is not installed in this environment.",
            )

        try:
            creds, _ = google.auth.default(
                scopes=["https://www.googleapis.com/auth/cloud-platform"]
            )
            self._credentials = creds
            if not creds.valid:
                auth_req = google.auth.transport.requests.Request()
                creds.refresh(auth_req)
            if not creds.token:
                raise ValueError("Credentials token is empty after refresh")
            return str(creds.token)
        except HTTPException:
            raise
        except Exception as exc:
            logger.error("Failed to acquire Google Application Default Credentials: %s", type(exc).__name__)
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Google Cloud credentials are not available in this environment.",
            )

    def _build_endpoint_url(self) -> str:
        """Construct the Vertex AI :rawPredict endpoint URL."""
        return (
            f"https://{self.settings.gcp_region}-aiplatform.googleapis.com/v1/"
            f"projects/{self.settings.gcp_project_id}/locations/{self.settings.gcp_region}/"
            f"endpoints/{self.settings.vertex_endpoint_id}:rawPredict"
        )

    def _build_payload(
        self,
        model: RegisteredModel,
        messages: list[ChatMessage],
        temperature: float = 0.7,
        max_tokens: int | None = None,
    ) -> dict[str, Any]:
        """Construct standard OpenAI Chat Completions payload compatible with vLLM."""
        model_name = getattr(model, "provider_model_id", None) or model.model_id
        payload: dict[str, Any] = {
            "model": model_name,
            "messages": [{"role": m.role, "content": m.content} for m in messages],
            "temperature": temperature,
            "stream": False,
        }
        if max_tokens is not None:
            payload["max_tokens"] = max_tokens
        return payload

    async def predict(
        self,
        model: RegisteredModel,
        messages: list[ChatMessage],
        temperature: float = 0.7,
        max_tokens: int | None = None,
    ) -> PredictionResult:
        if not self.settings.vertex_configured:
            logger.error("Vertex AI prediction invoked but server configuration is incomplete")
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Vertex AI prediction service is not configured in this environment.",
            )

        token = self._resolve_token()
        url = self._build_endpoint_url()
        payload = self._build_payload(model, messages, temperature, max_tokens)
        headers = {
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
        }

        start_time = time.monotonic()
        try:
            if self._client is not None:
                resp = await self._client.post(
                    url,
                    json=payload,
                    headers=headers,
                    timeout=self.timeout_seconds,
                )
            else:
                async with httpx.AsyncClient(timeout=self.timeout_seconds) as client:
                    resp = await client.post(
                        url,
                        json=payload,
                        headers=headers,
                    )
        except httpx.TimeoutException as exc:
            elapsed_ms = max(1, int((time.monotonic() - start_time) * 1000))
            logger.warning(
                "Upstream Vertex AI timed out after %d ms: %s",
                elapsed_ms,
                type(exc).__name__,
            )
            raise HTTPException(
                status_code=status.HTTP_504_GATEWAY_TIMEOUT,
                detail="Upstream model prediction service timed out.",
            )
        except Exception as exc:
            elapsed_ms = max(1, int((time.monotonic() - start_time) * 1000))
            logger.error(
                "Upstream Vertex AI request failed after %d ms: %s",
                elapsed_ms,
                type(exc).__name__,
            )
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail="Upstream model prediction service failed.",
            )

        elapsed_ms = max(1, int((time.monotonic() - start_time) * 1000))

        if resp.status_code != 200:
            logger.error(
                "Upstream Vertex AI returned HTTP %d (elapsed=%d ms)",
                resp.status_code,
                elapsed_ms,
            )
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail="Upstream model prediction service failed.",
            )

        try:
            data = resp.json()
            choices = data.get("choices")
            if not choices or not isinstance(choices, list):
                raise ValueError("Missing or invalid 'choices' list in response")

            first_choice = choices[0]
            message_obj = first_choice.get("message", {})
            content = str(message_obj.get("content") or "")
            finish_reason = str(first_choice.get("finish_reason") or "stop")

            usage = data.get("usage")
            if usage is None or not isinstance(usage, dict):
                raise ValueError("Missing or invalid 'usage' metadata in upstream model response.")

            if "prompt_tokens" not in usage or "completion_tokens" not in usage:
                raise ValueError("Incomplete 'usage' metadata: missing prompt_tokens or completion_tokens.")

            raw_prompt_tokens = usage["prompt_tokens"]
            raw_completion_tokens = usage["completion_tokens"]

            if isinstance(raw_prompt_tokens, bool) or isinstance(raw_completion_tokens, bool):
                raise TypeError("Token counts in usage must be integers, not booleans.")

            try:
                tokens_in = int(raw_prompt_tokens)
                tokens_out = int(raw_completion_tokens)
            except (ValueError, TypeError) as conv_exc:
                raise ValueError(f"Non-integer token counts in usage metadata: {conv_exc}")

            if tokens_in < 0 or tokens_out < 0:
                raise ValueError(f"Negative token counts: tokens_in={tokens_in}, tokens_out={tokens_out}")

            # Every chat completion request includes prompt messages; prompt_tokens must be >= 1.
            # Never silently allow zero prompt tokens for billable inference.
            if tokens_in == 0:
                raise ValueError("Zero prompt_tokens reported by upstream provider for chat completion.")

            # Consistency check: non-empty generated text cannot consume zero completion tokens.
            if content.strip() and tokens_out == 0:
                raise ValueError("Inconsistent usage: non-empty completion text generated with zero completion tokens.")

            return PredictionResult(
                content=content,
                tokens_in=tokens_in,
                tokens_out=tokens_out,
                latency_ms=elapsed_ms,
                finish_reason=finish_reason[:32],
            )
        except Exception as exc:
            logger.error(
                "Failed to parse upstream Vertex AI response JSON: %s (%s)",
                type(exc).__name__,
                exc,
            )
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail="Upstream model prediction returned an invalid response format.",
            )


def get_model_provider(settings: Settings) -> BaseModelProvider:
    """Return the active model provider based on application configuration.

    In production or staging, VertexModelProvider is always selected to enforce
    fail-closed behavior when Vertex AI settings are missing or incomplete.
    """
    if settings.is_production:
        return VertexModelProvider(settings)
    if not settings.vertex_configured:
        return MockModelProvider()
    return VertexModelProvider(settings)
